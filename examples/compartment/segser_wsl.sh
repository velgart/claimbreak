#!/usr/bin/env bash
# segser_wsl.sh -- segmentation series on a Linux or WSL workstation.
# The same cells re-segmented from their nuclei at 0-15 um (examples/compartment/reexpand.py), labeled per mask, then
# compartment compare/summary per mask, the series table (segseries_summary.py) and protein CD8 recall per mask on the
# IHC sections. Uses the claimbreak clone and venv of ihc_wsl.sh (~/claimbreak_work/ihc/claimbreak, ~/claimbreak_work/ihc/venv), so run
# `bash ihc_wsl.sh setup` first. Never touches other clones.
#   bash segser_wsl.sh check     sections found, reference, disk, settings of the earlier lung labels
#   bash segser_wsl.sh lung      re-expand + label every lung section (PAR sections at a time; resumable)
#   bash segser_wsl.sh lungsum   compare/summary per mask, series table, IHC truth per mask; harvest ~/segser_lung_<time>.tgz
#   bash segser_wsl.sh kidney    the same for the kidney regions (AIN, multimodal segmentation), with its summary + harvest
#   bash segser_wsl.sh drive     copy labels, tables and logs to the data drive (E:)
# Environment: RAW (lung raw, default ~/claimbreak_data/Bilous/raw), REF (lung reference), SECTIONS (comma list; default all),
# RADII (default 0,1,2,3,5,7,10,15), PAR (sections in parallel, default 2), KEEP_H5AD=1 (keep mask .h5ad files;
# default: deleted once a section is labeled, they are regenerated by reexpand.py in minutes), LABEL_OPTS (extra
# options for `compartment label`), KRAW / KREF / KH5AD (kidney raw, reference, converted regions for obs),
# DRIVE (default /mnt/e).
set -uo pipefail
I=~/claimbreak_work/ihc
CB=$I/claimbreak
PY=$I/venv/bin/python
CBX=$I/venv/bin/claimbreak
X=$CB/examples/compartment
DRIVE=${DRIVE:-/mnt/e}
RADII=${RADII:-0,1,2,3,5,7,10,15}
PAR=${PAR:-2}
export OMP_NUM_THREADS=4 OPENBLAS_NUM_THREADS=4 MKL_NUM_THREADS=4
step=${1:-}
fail() { echo "STOP: $*"; exit 1; }
[[ -x $PY && -x $CBX ]] || fail "no venv at $I/venv; run ihc_wsl.sh setup first"
[[ -f $X/reexpand.py ]] || fail "this clone has no reexpand.py; run ihc_wsl.sh setup"

# tissue settings: W (work folder), RAW, REF, LEVEL, UNITS (regex), LABEL (label options), IHC (sections with IHC)
set_lung() {
  W=~/claimbreak_work/segser/lung; RAW=${RAW:-~/claimbreak_data/Bilous/raw}
  REF=${REF:-$DRIVE/fibrosis/Bilous/ref/4ca422ae-e4ad-4884-9073-7c3799cd9143.h5ad}
  LEVEL=L2m; UNITS='L\d(?=_L)'; LABEL="--levels L2m ${LABEL_OPTS:-}"; OBS=""
  IHC=GSM9509145_NSCLC_lung_L1_L1,GSM9509149_NSCLC_lung_L3_L3
}
set_kidney() {
  W=~/claimbreak_work/segser/kidney; RAW=${KRAW:-$DRIVE/fibrosis/AIN/raw}
  REF=${KREF:-$DRIVE/fibrosis/AIN/ref/kidney_census.h5ad}
  LEVEL=L1; UNITS='Region\d+'
  LABEL="--levels L1 --ref-levels L1=coarse --ref-merge '' --ref-donor donor_id --gamma-iter 0 ${LABEL_OPTS:-}"
  OBS=${KH5AD:-$DRIVE/fibrosis/AIN/h5ad_regions}; IHC=""
}
sections() {   # sections with transcripts, cells and nucleus boundaries; Lung and Custom IO panels before 5K
  if [[ -n ${SECTIONS:-} ]]; then tr , '\n' <<<"$SECTIONS"; return; fi
  for f in $RAW/*_nucleus_boundaries.parquet*; do
    s=$(basename $f); s=${s%_nucleus_boundaries.parquet*}
    ls $RAW/${s}_transcripts.parquet* $RAW/${s}_cells.parquet* >/dev/null 2>&1 && echo $s
  done | awk '{k = /_5k_/ ? 1 : 0; print k "\t" $0}' | sort | cut -f2
}

one_section() {   # re-expand one section, label every mask, delete its mask files
  local s=$1 m o=""
  [[ -f $W/done/$s ]] && { echo "$s: done before"; return 0; }
  [[ -n $OBS && -f $OBS/$s.h5ad ]] && o="--obs-from $OBS/$s.h5ad"
  rm -rf $W/h5ad/*/$s.h5ad $W/h5ad/$s.cells.csv.gz $W/h5ad/$s.reexpand.json $W/tmp/$s
  mkdir -p $W/tmp/$s
  $PY -u $X/reexpand.py --raw $RAW --sample $s --out $W/h5ad --tmp $W/tmp/$s --radii $RADII $o \
    > $W/logs/reexpand_$s.log 2>&1 || { echo "$s: reexpand FAILED"; tail -5 $W/logs/reexpand_$s.log; return 1; }
  for m in $(ls $W/h5ad | grep -E '^(r[0-9.]+|platform)$'); do
    [[ -f $W/h5ad/$m/$s.h5ad ]] || continue
    rm -f $W/labels/$m/$s.labels.csv.gz
    eval $CBX compartment label --ref $W/ref.h5ad --inputs $W/h5ad/$m/$s.h5ad --out $W/labels/$m \
      --arms whole,nucleus,nucA,nucB,wholeB $LABEL >> $W/logs/label_$s.log 2>&1 \
      || { echo "$s: label $m FAILED"; tail -5 $W/logs/label_$s.log; return 1; }
  done
  [[ ${KEEP_H5AD:-0} == 1 ]] || rm -f $W/h5ad/*/$s.h5ad
  rm -rf $W/tmp/$s
  touch $W/done/$s
  echo "$s: done $(date +%H:%M)"
}

run_tissue() {
  mkdir -p $W/{h5ad,labels,logs,tmp,done}
  [[ -f $REF ]] || fail "reference $REF not found"
  [[ -f $W/ref.h5ad ]] || cp $REF $W/ref.h5ad
  local S=($(sections)); (( ${#S[@]} )) || fail "no section with nucleus boundaries in $RAW"
  echo "$(date +%H:%M) ${#S[@]} sections, $PAR at a time, radii $RADII; logs in $W/logs"
  local bad=0
  for s in "${S[@]}"; do
    while (( $(jobs -rp | wc -l) >= PAR )); do wait -n || bad=1; done
    one_section $s &
  done
  while (( $(jobs -rp | wc -l) > 0 )); do wait -n || bad=1; done
  echo "$(date +%H:%M) sections finished: $(ls $W/done | wc -l) of ${#S[@]}"
  (( bad == 0 )) || echo "some sections failed (see above); rerun the same command to retry them"
}

summarise() {
  local m
  for m in $(ls $W/labels); do
    [[ -d $W/labels/$m/summary ]] && continue
    echo "$(date +%H:%M) compare + summary: mask $m" 
    rm -rf $W/labels/$m/compare
    $CBX compartment compare --labels $W/labels/$m --out $W/labels/$m/compare --levels $LEVEL \
      --comparisons "nucB|nucA,wholeB|nucA" > $W/logs/compare_$m.log 2>&1 || { echo "compare $m FAILED"; tail -5 $W/logs/compare_$m.log; continue; }
    $CBX compartment summary --compare $W/labels/$m/compare --out $W/labels/$m/summary --level $LEVEL \
      --unit-pattern "$UNITS" > $W/logs/summary_$m.log 2>&1 || { echo "summary $m FAILED"; tail -5 $W/logs/summary_$m.log; }
  done
  rm -rf $W/summary $W/ihc_labels
  local c=""
  [[ -n $IHC ]] && c="--combine-out $W/ihc_labels --samples $IHC"
  $PY -u $X/segseries_summary.py --labels-root $W/labels --h5ad-root $W/h5ad --level $LEVEL --unit-pattern "$UNITS" \
    --out $W/summary $c 2>&1 | tee $W/logs/segseries.log
  if [[ -n $IHC ]]; then
    local M=""
    for r in $I/reg_L1_c1 $I/reg_L3_c5; do [[ -f $r/matches.csv.gz ]] && M=$M${M:+,}$r; done
    if [[ -n $M ]]; then
      rm -rf $W/truth_masks
      $PY -u $CB/examples/correction/ihc_truth.py truth --matches $M --labels $W/ihc_labels --out $W/truth_masks \
        --max-match-um 2 --hybrid ${HYBRID:-nucleus:whole} > $W/logs/truth_masks.log 2>&1 || { echo "IHC truth per mask FAILED"; tail -5 $W/logs/truth_masks.log; }
      $PY - $W/truth_masks <<'EOF2'
import sys, pandas as pd
T = pd.read_csv(sys.argv[1] + "/t6_counts.csv")
T = T[T.protein_class.isin(["CD8any", "CD8iso"])]
print("protein CD8 recall as T_NK per mask (rows: arm; r<d> = expansion by d um, r<d>B = the same at nucleus depth)")
print(T.pivot_table(index="arm", columns=["protein_class", "sample"], values="recall").round(3).to_string())
if "recall_all" in T:   # unlabelled cells counted as misses, and the hybrid arm nucleus+whole
    q = T[(T.protein_class == "CD8any") & T.arm.isin(["nucleus", "whole", "nucleus+whole", "wholeB", "r0B"])]
    print("CD8any over all matched CD8 cells (unlabelled = missed): recall_all, labelled_share")
    print(q.pivot_table(index="arm", columns="sample", values=["recall_all", "labelled_share"]).round(3).to_string())
EOF2
    else
      echo "no IHC matches in $I (run ihc_wsl.sh A first); IHC per mask skipped"
    fi
  fi
  local Z=~/segser_$(basename $W)_$(date +%Y%m%d_%H%M).tgz
  (cd $W && tar czf $Z logs summary h5ad/*.reexpand.json labels/*/summary labels/*/*.meta.json \
     $( [[ -d truth_masks ]] && echo truth_masks ) 2>/dev/null)
  ls -lh $Z; echo "copy to Windows: cp $Z /mnt/c/Users/$USER/Downloads/"
}

case $step in
  check)
    for t in lung kidney; do
      set_$t; echo "== $t: raw $RAW, reference $REF"
      [[ -f $REF ]] && echo "  reference ok" || echo "  reference MISSING"
      S=($(sections)); echo "  ${#S[@]} sections with nucleus boundaries: ${S[*]:0:14}"
    done
    echo "== disk"; df -h ~ | tail -1
    echo "== earlier lung labels (bilous_v4) settings, for comparison with LABEL_OPTS"
    f=$(ls $I/bilous_v4/*.meta.json 2>/dev/null | head -1)
    [[ -n $f ]] && $PY -c "import json,sys; d=json.load(open('$f')); print({k: v for k, v in d.items() if any(s in k for s in ('gamma','floor','min_counts','level','merge','markers','exclude','seed'))})" \
      || echo "  no meta.json in $I/bilous_v4"
    $PY -c "import claimbreak; print('claimbreak', claimbreak.__version__)" ;;
  lung)    set_lung; run_tissue ;;
  lungsum) set_lung; summarise ;;
  kidney)  set_kidney; run_tissue && summarise ;;
  drive)
    D=$DRIVE/fibrosis/segser; mkdir -p $D || fail "drive not mounted at $DRIVE"
    for t in lung kidney; do
      [[ -d ~/claimbreak_work/segser/$t/labels ]] || continue
      mkdir -p $D/$t
      (cd ~/claimbreak_work/segser/$t && tar cf - labels summary logs h5ad/*.cells.csv.gz h5ad/*.reexpand.json \
         $( [[ -d truth_masks ]] && echo truth_masks ) $( [[ -d ihc_labels ]] && echo ihc_labels ) 2>/dev/null) \
        | (cd $D/$t && tar xf - -m --no-same-owner --no-same-permissions) && echo "$t -> $D/$t ($(du -sh $D/$t | cut -f1))"
    done
    mkdir -p $DRIVE/fibrosis/Bilous/ihc_truth
    for d in truth_d2 truth_d2_noaf truth_d1 truth_d1_noaf truth_c_d2 truth_c_d2_noaf reg_diag; do
      [[ -d $I/$d ]] && cp -r --no-preserve=all $I/$d $DRIVE/fibrosis/Bilous/ihc_truth/ && echo "IHC $d -> $DRIVE/fibrosis/Bilous/ihc_truth/$d"
    done
    for d in $I/reg_L1_c1 $I/reg_L3_c5; do
      mkdir -p $DRIVE/fibrosis/Bilous/ihc_truth/$(basename $d) && cp $d/register.json $d/matches.csv.gz \
        $DRIVE/fibrosis/Bilous/ihc_truth/$(basename $d)/ 2>/dev/null && echo "IHC $(basename $d) matches -> drive"
    done
    sync; echo "drive copy done: $D and $DRIVE/fibrosis/Bilous/ihc_truth" ;;
  *) echo "usage: bash segser_wsl.sh check|lung|lungsum|kidney|drive" ;;
esac
